/** Which criterion each tag belongs to. "other" keeps the model's criterion. */
export const TAG_CRITERION: Record<ErrorTag, CriterionKey | null> = {
  articles: "grammar",
  subject_verb_agreement: "grammar",
  verb_tense: "grammar",
  prepositions: "grammar",
  plural_countability: "grammar",
  sentence_structure: "grammar",
  run_on_or_fragment: "grammar",
  punctuation: "grammar",
  word_choice: "lexical",
  word_form: "lexical",
  collocation: "lexical",
  spelling: "lexical",
  repetition: "lexical",
  register_tone: "lexical",
  linking_words: "coherence",
  paragraphing: "coherence",
  referencing: "coherence",
  progression: "coherence",
  task_coverage: "task",
  overview_missing: "task",
  data_accuracy: "task",
  position_unclear: "task",
  idea_development: "task",
  off_topic: "task",
  // In letters, an inappropriate tone is judged under Task Achievement.
  letter_purpose_or_tone: "task",
  other: null,
};

/** Share of letters that must be Latin for a script to count as possibly English. */
export const MIN_LATIN_SHARE = 0.5;
/** A script with this many words or fewer is band 1 on every criterion. */
export const MAX_WORDS_FOR_BAND_1 = 20;

export interface PostprocessInput {
  output: GraderOutput;
  task: WritingTask;
  script: string;
  feedbackLang: FeedbackLang;
  model: string;
  includeModelAnswer: boolean;
  customVisual?: CustomVisualInput;
  /** Report id to embed (generated by the caller before saving), or null. */
  id: string | null;
  /** ISO timestamp. */
  now: string;
}

type Adjustment = NonNullable<GradeReport["adjustments"]>[number];

function capCriterion(
  bands: Record<CriterionKey, number>,
  key: CriterionKey,
  max: number,
  rule: string,
  reason: string,
  adjustments: Adjustment[],
): void {
  if (bands[key] > max) {
    adjustments.push({ criterion: key, from: bands[key], to: max, rule, reason });
    bands[key] = max;
  }
}

/** Deduplicate a list of located issues: same span + same tag, or same span + same suggestion. */
function dedupeIssues(issues: InlineIssue[]): InlineIssue[] {
  const seen = new Set<string>();
  const out: InlineIssue[] = [];
  for (const i of issues) {
    const k1 = `${i.start}:${i.end}:${i.tag}`;
    const k2 = `${i.start}:${i.end}:s:${i.suggestion.toLowerCase()}`;
    if (seen.has(k1) || seen.has(k2)) continue;
    seen.add(k1);
    seen.add(k2);
    out.push(i);
  }
  return out;
}

/** Locate each issue; prefer an occurrence not already used by an identical quote. */
function locateIssues(script: string, raw: GraderOutput["issues"]): { located: InlineIssue[]; dropped: number } {
  const used: Array<[number, number]> = [];
  const located: InlineIssue[] = [];
  let dropped = 0;
  for (const issue of raw) {
    let m = locateQuote(script, issue.quote);
    // If this exact span is already taken by an earlier issue with the same quote, look further on.
    let guard = 0;
    while (m && used.some(([s, e]) => s === m!.start && e === m!.end) && guard++ < 5) {
      const next = locateQuote(script, issue.quote, m.end);
      if (!next) break;
      m = next;
    }
    if (!m) {
      dropped++;
      continue;
    }
    used.push([m.start, m.end]);
    const mapped = TAG_CRITERION[issue.tag];
    located.push({
      quote: script.slice(m.start, m.end),
      start: m.start,
      end: m.end,
      criterion: mapped ?? issue.criterion,
      tag: issue.tag,
      explanation: issue.explanation,
      suggestion: issue.suggestion,
    });
  }
  return { located, dropped };
}

/** Rewrite: original must be a paragraph of the script; repair by best-overlap paragraph, or drop. */
function resolveRewrite(script: string, rw: GraderOutput["rewrite"]): GradeReport["rewrite"] {
  if (!rw) return null;
  const changes = rw.changes.slice(0, OUTPUT_LIMITS.maxRewriteChanges);
  const m = locateQuote(script, rw.original);
  if (m) return { original: script.slice(m.start, m.end), improved: rw.improved, changes };
  // The model may have tidied whitespace or a typo. Accept the paragraph that shares ≥ 80 % of its words.
  const words = (s: string) => s.toLowerCase().match(/[\p{L}\p{N}']+/gu) ?? [];
  const target = words(rw.original);
  if (target.length === 0) return null;
  let best: { text: string; score: number } | null = null;
  for (const p of splitParagraphs(script)) {
    const pw = words(p.text);
    const set = new Set(pw);
    const hit = target.filter((w) => set.has(w)).length;
    const score = Math.min(hit / target.length, hit / Math.max(pw.length, 1));
    if (!best || score > best.score) best = { text: p.text, score };
  }
  if (best && best.score >= 0.8) return { original: best.text, improved: rw.improved, changes };
  return null;
}

/**
 * CEILING RULES (applied in this order; each is recorded in `adjustments`):
 *   R1 not_english  — fewer than half the letters are Latin script → every criterion 0
 *                     (descriptor rule: a script not in English is band 0).
 *   R2 max_20_words — 20 words or fewer → every criterion at most 1 (descriptor rule).
 *   R3 severely_under_length — under 2/3 of the minimum (T1 < 100, T2 < 167 words)
 *                     → task criterion at most 5. CONSERVATIVE: such a script cannot
 *                     cover or develop the task adequately, which is the band-5 feature.
 *   R4 off_topic    — model flagged off_topic → task criterion at most 4 ("tangential").
 *   R5 checklist    — a checklist verdict "no"/"partly" on an item with caps (rubric.ts)
 *                     → task criterion at most that cap. This makes the band consistent
 *                     with the model's own checklist (e.g. "no overview" but TA 7 is
 *                     impossible).
 * Language criteria are never capped for length or content: descriptors judge
 * the language that is there.
 */
export function buildReport(input: PostprocessInput): GradeReport {
  const { output, task, script } = input;
  const rules = TASK_RULES[task.taskType];
  const wordCount = countWords(script);
  const paragraphCount = splitParagraphs(script).length;
  const overlap = promptOverlap(script, [task.prompt, ...task.bullets].join("\n"));
  const latinShare = latinLetterShare(script);

  // ── flags ──
  const flags = new Set<ReportFlag>();
  for (const f of output.flags) flags.add(f);
  if (wordCount < rules.minWords) flags.add("under_length");
  const severeLimit = Math.ceil(rules.minWords * SEVERE_UNDER_LENGTH_RATIO);
  if (wordCount < severeLimit) flags.add("severely_under_length");
  if (latinShare < MIN_LATIN_SHARE) flags.add("not_english");
  if (overlap.copiedWords >= 15 || (overlap.copiedWords >= 8 && overlap.ratio >= 0.15)) flags.add("copied_from_prompt");
  const noVisual =
    task.taskType === "task1_academic" && task.visuals.length === 0 && !input.customVisual?.imageDataUrl && !input.customVisual?.description;
  if (noVisual) flags.add("visual_not_available");
  if (task.taskType !== "task1_academic") flags.delete("visual_not_available");

  // Detected variant: bank tasks are labelled by us and trusted; others may be mislabelled.
  let variantDetected: TaskVariant | null = null;
  if (output.variantDetected !== task.variant && task.source !== "bank") {
    variantDetected = output.variantDetected;
    flags.add("wrong_task_variant");
  }

  // ── checklist (labels from the rubric; not_applicable items dropped) ──
  const defs = checklistFor(task.variant);
  const checklist: ChecklistItem[] = [];
  for (const def of defs) {
    const v = output.checklist.find((c) => c.id === def.id);
    if (!v || v.met === "not_applicable") continue;
    checklist.push({ id: def.id, label: def.label, met: v.met, note: v.note });
  }

  // ── bands and ceilings ──
  const bands = {} as Record<CriterionKey, number>;
  for (const k of CRITERION_KEYS) bands[k] = output.criteria[k].band;
  const adjustments: Adjustment[] = [];
  const taskLabel = rules.taskCriterionLabel;

  if (latinShare < MIN_LATIN_SHARE) {
    for (const k of CRITERION_KEYS) capCriterion(bands, k, 0, "not_english", "The script is not written in English; such scripts are rated band 0.", adjustments);
  }
  if (wordCount <= MAX_WORDS_FOR_BAND_1) {
    for (const k of CRITERION_KEYS)
      capCriterion(bands, k, 1, "max_20_words", "Scripts of 20 words or fewer are rated band 1.", adjustments);
  }
  if (flags.has("severely_under_length")) {
    capCriterion(bands, "task", 5, "severely_under_length", `Far below the ${rules.minWords}-word minimum: ${taskLabel} is at most 5.`, adjustments);
  }
  if (flags.has("off_topic")) {
    capCriterion(bands, "task", 4, "off_topic", `The response does not address the question: ${taskLabel} is at most 4.`, adjustments);
  }
  for (const def of defs) {
    const v = output.checklist.find((c) => c.id === def.id);
    if (!v || !def.caps) continue;
    const cap = v.met === "no" ? def.caps.no : v.met === "partly" ? def.caps.partly : undefined;
    if (cap !== undefined)
      capCriterion(
        bands,
        "task",
        cap,
        `checklist:${def.id}:${v.met}`,
        `"${def.label}" ${v.met === "no" ? "is not met" : "is only partly met"}: ${taskLabel} is at most ${cap}.`,
        adjustments,
      );
  }

  const { raw: overallRaw, overall } = overallFromCriteria(bands);

  // ── criteria with located evidence ──
  let evidenceDropped = 0;
  let criteriaWithoutEvidence = 0;
  const criteria = {} as Record<CriterionKey, CriterionResult>;
  for (const k of CRITERION_KEYS) {
    const c = output.criteria[k];
    const evidence: string[] = [];
    for (const q of c.evidence) {
      const m = locateQuote(script, q);
      if (!m) {
        evidenceDropped++;
        continue;
      }
      const text = script.slice(m.start, m.end);
      if (!evidence.includes(text)) evidence.push(text);
      if (evidence.length >= OUTPUT_LIMITS.maxEvidencePerCriterion) break;
    }
    if (evidence.length === 0 && wordCount > MAX_WORDS_FOR_BAND_1) criteriaWithoutEvidence++;
    criteria[k] = {
      key: k,
      label: k === "task" ? taskLabel : CRITERION_LABELS[k],
      band: bands[k],
      rationale: c.rationale,
      evidence,
      toNextBand: c.toNextBand,
    };
  }

  // ── issues ──
  const { located, dropped } = locateIssues(script, output.issues);
  const issues = dedupeIssues(located)
    .slice(0, OUTPUT_LIMITS.maxIssues)
    .sort((a, b) => (a.start as number) - (b.start as number));
  const errorTagCounts: Partial<Record<ErrorTag, number>> = {};
  for (const i of issues) errorTagCounts[i.tag] = (errorTagCounts[i.tag] ?? 0) + 1;

  // ── confidence ──
  const lowFlags: ReportFlag[] = ["severely_under_length", "off_topic", "not_english", "memorised_or_template", "visual_not_available"];
  const mediumFlags: ReportFlag[] = ["under_length", "copied_from_prompt", "wrong_task_variant"];
  const issueTotal = output.issues.length;
  const dropRate = issueTotal ? dropped / issueTotal : 0;
  let confidence: GradeReport["confidence"] = "high";
  if (
    lowFlags.some((f) => flags.has(f)) ||
    wordCount <= MAX_WORDS_FOR_BAND_1 ||
    (issueTotal >= 4 && dropRate > 0.5)
  ) {
    confidence = "low";
  } else if (
    mediumFlags.some((f) => flags.has(f)) ||
    dropRate > 0.2 ||
    criteriaWithoutEvidence > 0 ||
    adjustments.length > 0 ||
    (task.taskType === "task1_academic" && task.source === "custom")
  ) {
    confidence = "medium";
  }

  const report: GradeReport = {
    id: input.id,
    contractVersion: CONTRACT_VERSION,
    graderVersion: GRADER_VERSION,
    model: input.model,
    createdAt: input.now,
    task,
    variantDetected,
    feedbackLang: input.feedbackLang,
    script,
    wordCount,
    paragraphCount,
    criteria,
    overallRaw,
    overall,
    checklist,
    flags: [...flags],
    confidence,
    summary: output.summary,
    strengths: output.strengths.slice(0, OUTPUT_LIMITS.maxStrengths),
    priorities: output.priorities.slice(0, OUTPUT_LIMITS.maxPriorities),
    issues,
    errorTagCounts,
    rewrite: resolveRewrite(script, output.rewrite),
    modelAnswer: input.includeModelAnswer ? output.modelAnswer : null,
  };
  if (adjustments.length) report.adjustments = adjustments;
  // evidenceDropped is diagnostic only (logged by the caller through reportDiagnostics).
  void evidenceDropped;
  return report;
}

/** Numbers worth logging per grading (no student text). */
export function reportDiagnostics(output: GraderOutput, report: GradeReport) {
  return {
    issuesProposed: output.issues.length,
    issuesKept: report.issues.length,
    evidenceProposed: CRITERION_KEYS.reduce((n, k) => n + output.criteria[k].evidence.length, 0),
    evidenceKept: CRITERION_KEYS.reduce((n, k) => n + report.criteria[k].evidence.length, 0),
    adjustments: report.adjustments?.length ?? 0,
    confidence: report.confidence,
    flags: report.flags,
  };
}

/** Legacy `criteria` column shape: {task,coherence,lexical,grammar:{band,comment,label}}. */
export function legacyCriteria(report: GradeReport): Record<CriterionKey, { band: number; comment: string; label: string }> {
  const out = {} as Record<CriterionKey, { band: number; comment: string; label: string }>;
  for (const k of CRITERION_KEYS) {
    const c = report.criteria[k];
    out[k] = { band: c.band, comment: c.rationale, label: c.label };
  }
  return out;
}

/** Row for ielts_writing_reports (without user_id / session_id). */
export function reportRow(report: GradeReport) {
  const promptText = report.task.bullets.length
    ? `${report.task.prompt}\n${report.task.bullets.map((b) => `• ${b}`).join("\n")}`
    : report.task.prompt;
  return {
    id: report.id,
    task_type: report.task.taskType,
    prompt: promptText,
    chart: report.task.visuals.length ? report.task.visuals : null,
    essay: report.script,
    word_count: report.wordCount,
    criteria: legacyCriteria(report),
    overall_band: report.overall,
    comments: report,
    model_answer: report.modelAnswer,
  };
}

/** Light structural check for a GradeReport read back from the database. */
export function isGradeReport(x: unknown): x is GradeReport {
  if (typeof x !== "object" || x === null) return false;
  const r = x as Record<string, unknown>;
  if (typeof r.contractVersion !== "number" || typeof r.script !== "string" || typeof r.overall !== "number") return false;
  if (typeof r.task !== "object" || r.task === null) return false;
  const c = r.criteria as Record<string, unknown> | undefined;
  return !!c && CRITERION_KEYS.every((k) => typeof c[k] === "object" && c[k] !== null);
}

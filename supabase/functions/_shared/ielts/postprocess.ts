/**
 * Validated model output → GradeReport. Pure and deterministic.
 *
 * What the server decides (never the model):
 *   - overallRaw / overall (bandMath), from the criterion bands AFTER ceilings;
 *     any overall the model might add is ignored (it is not even in the schema).
 *   - word and paragraph counts, length flags, wrong_task_variant, the
 *     non-Latin-script check, visual_not_available when there is no visual.
 *   - quote offsets. POLICY: an issue whose quote cannot be found in the
 *     script, even with the tolerant matcher, is DROPPED (never shown with
 *     invented or null offsets), because the product promise is feedback on
 *     the student's own sentences and an unfindable quote is usually a
 *     paraphrase or a hallucination. As a result `start`/`end` are never null
 *     in reports built here; the contract still allows null for other
 *     producers. Evidence quotes that cannot be found are dropped the same way.
 *     Located quotes are replaced by the exact script substring.
 *   - tag → criterion mapping (spelling is always lexical, etc.), dedupe,
 *     tag counts, list caps.
 *   - ceilings (documented in CEILING RULES below) and confidence.
 */

